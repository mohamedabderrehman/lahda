function isPointInPolygon(lat: number, lng: number, polygon: [number, number][]): boolean {
  let inside = false;
  const n = polygon.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const [yi, xi] = polygon[i];
    const [yj, xj] = polygon[j];
    if (
      yi > lat !== yj > lat &&
      lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    ) {
      inside = !inside;
    }
  }
  return inside;
}

export function isInsideDeliveryZone(lat: number, lng: number): boolean {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
  return isPointInPolygon(lat, lng, BABYLON_POLYGON);
}

function looksLikeBabylon(addr: Location.LocationGeocodedAddress): boolean {
  const parts = [
    addr.region,
    addr.subregion,
    addr.city,
    addr.district,
    addr.name,
    addr.street,
  ]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();

  // Common spellings: Babil / Babylon. Arabic: بابل
  return parts.includes('babylon') || parts.includes('babil') || parts.includes('بابل');
}

/**
 * Enhanced check that keeps the fast polygon check, but falls back to reverse
 * geocoding to cover all of محافظة بابل even if the polygon is imperfect.
 */
export async function isInsideDeliveryZoneEnhanced(lat: number, lng: number): Promise<boolean> {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
  if (isPointInPolygon(lat, lng, BABYLON_POLYGON)) return true;
  try {
    const res = await Location.reverseGeocodeAsync({ latitude: lat, longitude: lng });
    return Array.isArray(res) && res.some(looksLikeBabylon);
  } catch {
    return false;
  }
}

